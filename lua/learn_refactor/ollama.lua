-- Manage a local Ollama container (podman or docker compose), optionally with an NVIDIA GPU.
local config = require("learn_refactor.config")

local M = {}

local CONTAINER = "learn-refactor-ollama"

local function plugin_root()
  local src = debug.getinfo(1, "S").source:sub(2)
  return vim.fs.dirname(vim.fs.dirname(vim.fs.dirname(src))) -- <root>/lua/learn_refactor/ollama.lua
end

local function notify(msg, level)
  vim.notify("LearnRefactor/ollama: " .. msg, level or vim.log.levels.INFO)
end

function M.runtime()
  local want = config.options.ollama.runtime
  if want then
    return vim.fn.executable(want) == 1 and want or nil
  end
  for _, rt in ipairs({ "podman", "docker" }) do
    if vim.fn.executable(rt) == 1 then
      return rt
    end
  end
end

--- NVIDIA CDI spec generated by `nvidia-ctk cdi generate`
function M.has_cdi()
  for _, dir in ipairs({ "/etc/cdi", "/var/run/cdi" }) do
    for _, f in ipairs(vim.fn.glob(dir .. "/*", false, true)) do
      local fh = io.open(f, "r")
      if fh then
        local body = fh:read("*a")
        fh:close()
        if body:find("nvidia.com/gpu", 1, true) then
          return true
        end
      end
    end
  end
  return false
end

--- true/false/"missing-cdi": whether the GPU compose override should be used
function M.use_gpu(runtime)
  local g = config.options.ollama.gpu
  if g == false then
    return false
  end
  local ok = (runtime == "docker") or M.has_cdi()
  if g == true then
    return ok and true or "missing-cdi"
  end
  return ok and vim.fn.executable("nvidia-smi") == 1 -- "auto"
end

--- compose argv (without trailing command); also used by tests
function M.compose_args(runtime, gpu, network)
  local dir = plugin_root() .. "/docker"
  local args = { runtime, "compose", "-f", dir .. "/compose.yaml",
    "-f", dir .. (network == "host" and "/compose.host.yaml" or "/compose.bridge.yaml") }
  if gpu == true then
    vim.list_extend(args, { "-f", dir .. (runtime == "docker" and "/compose.gpu-docker.yaml" or "/compose.gpu.yaml") })
  end
  return args
end

local function port()
  return tostring(config.options.ollama.port)
end

local function run(args, opts, cb)
  vim.system(args, vim.tbl_extend("force", { text = true }, opts or {}), vim.schedule_wrap(cb))
end

--- cb(models: string[]|nil) - nil when the server is unreachable
local function list_models(cb)
  run({ "curl", "-sf", "--max-time", "2", "http://127.0.0.1:" .. port() .. "/api/tags" }, nil, function(res)
    if res.code ~= 0 then
      return cb(nil)
    end
    local ok, data = pcall(vim.json.decode, res.stdout)
    local names = {}
    if ok and type(data) == "table" then
      for _, m in ipairs(data.models or {}) do
        names[#names + 1] = m.name
      end
    end
    cb(names)
  end)
end

local function has_model(models, name)
  for _, m in ipairs(models) do
    if m == name or m == name .. ":latest" then
      return true
    end
  end
  return false
end

local function wait_ready(cb, tries)
  tries = tries or 60
  list_models(function(models)
    if models then
      return cb(models)
    end
    if tries <= 0 then
      return cb(nil)
    end
    vim.defer_fn(function()
      wait_ready(cb, tries - 1)
    end, 1000)
  end)
end

function M.pull(cb)
  local rt = M.runtime()
  local model = config.options.ollama.model
  if not rt then
    return cb(false, "no podman/docker found")
  end
  notify("pulling " .. model .. " (first time can take several minutes)...")
  run({ rt, "exec", CONTAINER, "ollama", "pull", model }, nil, function(res)
    if res.code ~= 0 then
      return cb(false, "pull failed: " .. (res.stderr or ""):sub(-300))
    end
    cb(true)
  end)
end

local function compose_up(rt, gpu, network, cb)
  local args = M.compose_args(rt, gpu, network)
  vim.list_extend(args, { "up", "-d" })
  notify(string.format("starting %s (%s, %s, %s network)...", CONTAINER, rt, gpu and "GPU" or "CPU", network))
  run(args, { env = { LEARN_REFACTOR_OLLAMA_PORT = port() } }, function(res)
    if res.code == 0 then
      return cb(true)
    end
    -- stdout first so the (more useful) stderr tail survives truncation; full text is kept for detection
    local out = (res.stdout or "") .. (res.stderr or "")
    cb(false, "compose up failed: " .. out, out:sub(-400))
  end)
end

--- start container (idempotent), wait for the API, pull the model when missing. cb(ok, err)
function M.up(cb)
  cb = cb or function(ok, err)
    if not ok then
      notify(err, vim.log.levels.ERROR)
    end
  end
  local rt = M.runtime()
  if not rt then
    return cb(false, "neither podman nor docker found in PATH")
  end
  local gpu = M.use_gpu(rt)
  if gpu == "missing-cdi" then
    return cb(false, "gpu = true but no NVIDIA CDI spec: install nvidia-container-toolkit and run "
      .. "`sudo nvidia-ctk cdi generate --output=/etc/cdi/nvidia.yaml` (or set ollama.gpu = false)")
  end
  local function after_up()
    wait_ready(function(models)
      if not models then
        return cb(false, "ollama did not become ready in 60s (check `" .. rt .. " logs " .. CONTAINER .. "`)")
      end
      if has_model(models, config.options.ollama.model) then
        return cb(true)
      end
      M.pull(cb)
    end)
  end
  local want = config.options.ollama.network
  compose_up(rt, gpu, want == "host" and "host" or "bridge", function(ok, err, tail)
    if ok then
      return after_up()
    end
    -- publishing ports needs netavark/nftables (or iptables); fall back to host networking
    local network_error = err:find("netavark", 1, true) or err:find("nftables", 1, true) or err:find("iptables", 1, true)
    if want == "auto" and network_error then
      notify("port publishing failed on this host, retrying with host networking")
      local down = M.compose_args(rt, false, "bridge")
      vim.list_extend(down, { "down" })
      return run(down, nil, function()
        compose_up(rt, gpu, "host", function(ok2, _, tail2)
          if ok2 then
            return after_up()
          end
          cb(false, "compose up failed: " .. tail2)
        end)
      end)
    end
    cb(false, "compose up failed: " .. tail)
  end)
end

function M.down()
  local rt = M.runtime()
  if not rt then
    return notify("neither podman nor docker found", vim.log.levels.ERROR)
  end
  local args = M.compose_args(rt, false, "bridge")
  vim.list_extend(args, { "down" })
  run(args, nil, function(res)
    notify(res.code == 0 and "stopped (model volume kept)" or ("down failed: " .. (res.stderr or "")),
      res.code == 0 and vim.log.levels.INFO or vim.log.levels.ERROR)
  end)
end

function M.status()
  local rt = M.runtime()
  local lines = { "runtime: " .. (rt or "none found") }
  if rt then
    local gpu = M.use_gpu(rt)
    lines[#lines + 1] = "gpu override: " .. (gpu == true and "yes" or gpu == "missing-cdi" and "NO CDI SPEC" or "no")
  end
  list_models(function(models)
    if not models then
      lines[#lines + 1] = "server: not reachable on 127.0.0.1:" .. port() .. " (:RefactorOllama up)"
      return notify(table.concat(lines, "\n"))
    end
    lines[#lines + 1] = "server: up, models: " .. (#models > 0 and table.concat(models, ", ") or "none")
    lines[#lines + 1] = "wanted model: " .. config.options.ollama.model
      .. (has_model(models, config.options.ollama.model) and " (present)" or " (missing, :RefactorOllama pull)")
    if not rt then
      return notify(table.concat(lines, "\n"))
    end
    run({ rt, "exec", CONTAINER, "ollama", "ps" }, nil, function(res)
      if res.code == 0 and res.stdout:match("%S") then
        lines[#lines + 1] = "loaded:\n" .. res.stdout
      end
      notify(table.concat(lines, "\n"))
    end)
  end)
end

--- is `base_url` the locally managed server?
function M.is_local(base_url)
  return base_url:find("127.0.0.1:" .. port(), 1, true) ~= nil or base_url:find("localhost:" .. port(), 1, true) ~= nil
end

--- start on demand before a generation; cb(ok, err). No-op when the server already answers.
function M.ensure(cb)
  list_models(function(models)
    if models and has_model(models, config.options.ollama.model) then
      return cb(true)
    end
    M.up(cb)
  end)
end

function M.command(sub)
  local actions = { up = M.up, down = M.down, status = M.status, pull = function() M.pull(function(ok, err)
    notify(ok and "model ready" or err, ok and vim.log.levels.INFO or vim.log.levels.ERROR)
  end) end }
  local fn = actions[sub or "status"]
  if not fn then
    return notify("usage: :RefactorOllama up|down|status|pull", vim.log.levels.WARN)
  end
  fn()
end

return M
